-- 00_setup.sql
USE ROLE ACCOUNTADMIN;

-- Cost guardrail: suspends the warehouse at 100% of quota
CREATE OR REPLACE RESOURCE MONITOR rm_olist
  WITH CREDIT_QUOTA = 40
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

-- Warehouse: X-Small, suspends after 60 seconds idle
CREATE WAREHOUSE IF NOT EXISTS wh_etl
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = rm_olist;

GRANT USAGE, OPERATE ON WAREHOUSE wh_etl TO ROLE SYSADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SYSADMIN;

-- Objects are created and owned by SYSADMIN
USE ROLE SYSADMIN;
USE WAREHOUSE wh_etl;
CREATE DATABASE IF NOT EXISTS olist_dw;
CREATE SCHEMA IF NOT EXISTS olist_dw.raw;
CREATE SCHEMA IF NOT EXISTS olist_dw.staging;
CREATE SCHEMA IF NOT EXISTS olist_dw.marts;
CREATE SCHEMA IF NOT EXISTS olist_dw.audit;

CREATE OR REPLACE FILE FORMAT olist_dw.raw.ff_csv
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL');

CREATE STAGE IF NOT EXISTS olist_dw.raw.stg_olist
  FILE_FORMAT = olist_dw.raw.ff_csv
  DIRECTORY = (ENABLE = TRUE);

-- Verify
SHOW SCHEMAS IN DATABASE olist_dw;
SHOW RESOURCE MONITORS;

